"""
Build the paper's summary tables from docs/results_of_record (no re-training).

  T2  cross-study summary: best snapshot model, best model with history, constant guess (mean error, m)
  T3  25x25 regression: best tree model at any depth against the GRU at h = 15 (three seeds)
  T5  15x15 grid baselines under clean and imperfect history: snapshot, XGBoost, 1D-CNN, GRU, HMM tracking filter

Each table is written as LaTeX (tabular only, to be wrapped by the paper) and as a Markdown preview.
Usage (from the repository root):
    .venv/Scripts/python experiments/09_grid_localization/docs/paper/tables/make_tables.py
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
REC = HERE.parents[1] / 'results_of_record'


def fmt(x, d=2):
    return '—' if x is None or (isinstance(x, float) and np.isnan(x)) else f'{x:.{d}f}'


# Constant guess on the 15x15 grid: mean distance of the test positions from the mean training position, computed
# 2026-10-24 from sim_data_multi_user_2026-10-13_11-23-48 (the walks are the same for both placements). A uniform
# distribution over cells would give 11.5 m; the walks visit the edge cells less often.
GRID_GUESS_M = 10.91


def write(name, header, rows, caption, colspec):
    md = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    md += ['| ' + ' | '.join(r) + ' |' for r in rows]
    (HERE / f'{name}.md').write_text(f'**{name}.** {caption}\n\n' + '\n'.join(md) + '\n', encoding='utf-8')
    esc = lambda s: s.replace('%', '\\%').replace('×', '$\\times$').replace('—', '--').replace('≥', '$\\geq$')
    tex = ['% generated by make_tables.py; do not edit by hand', f'\\begin{{tabular}}{{{colspec}}}', '\\hline',
           ' & '.join(esc(h) for h in header) + ' \\\\', '\\hline']
    tex += [' & '.join(esc(c) for c in r) + ' \\\\' for r in rows]
    tex += ['\\hline', '\\end{tabular}']
    (HERE / f'{name}.tex').write_text('\n'.join(tex) + '\n', encoding='utf-8')
    print(f'{name}: {len(rows)} rows')


# ── T2 cross-study summary ────────────────────────────────────────────────────
def t2():
    rows = []
    guess_g = GRID_GUESS_M
    names = {'xgboost': 'XGBoost', 'rf': 'RF', 'cnn': 'CNN', 'gru': 'GRU', 'random_forest': 'RF', 'lstm': 'LSTM'}
    for place, folder in (('centre', 'centre_mixed'), ('corner', 'ne_mixed')):
        parts = [pd.read_csv(REC / 'history_extended' / folder / 'history_extended.csv'),
                 pd.read_csv(REC / 'history_extended' / f'{folder}_wmgru' / 'history_extended_wmgru.csv')]
        d = pd.concat(parts)
        d = d[d['model'].isin(['xgboost', 'rf', 'cnn', 'gru'])]
        m = d.groupby(['model', 'experiment', 'h'])['mae'].mean().reset_index()
        for exp, aoa in (('BASE', 'no'), ('BASE_A', 'yes')):
            e = m[m['experiment'] == exp]
            s = e[e['h'] == 0].sort_values('mae').iloc[0]
            h = e[e['h'] > 0].sort_values('mae').iloc[0]
            rows.append(['15×15 grid, mixed', f'BS {place}', aoa, f"{fmt(s['mae'])} ({names[s['model']]})",
                         f"{fmt(h['mae'])} ({names[h['model']]}, h = {int(h['h'])})", fmt(guess_g, 1),
                         f"{100 * (1 - h['mae'] / s['mae']):.0f} %"])
    a = pd.read_csv(REC / 'regression_25x25_2026_10' / 'sequence_vs_trees' / 'all_mae.csv')
    seeds = []
    for s_ in ('umilos', 'nlos', 'mixed'):
        f = pd.read_csv(REC / 'regression_25x25_2026_10' / 'sequence_vs_trees' / f'{s_}_gru_h15_seeds12.csv')
        f['set'] = s_
        seeds.append(f)
    seeds = pd.concat(seeds)
    seeds['aoa'] = seeds['experiment'] == 'BASE_A'
    guess_r = json.loads((REC / 'error_audit' / 'regression25_mixed' / 'error_distribution.json').read_text())['BASE/all']['constant_guess_mean_m']
    for s_, label in (('umilos', 'UMi LOS'), ('nlos', 'uniform NLOS'), ('mixed', 'mixed')):
        for aoa in (False, True):
            e = a[(a['set'] == s_) & (a['aoa'] == aoa)].copy()
            g15 = e[(e['model'] == 'gru') & (e['h'] == 15)]['mae_m'].tolist() + \
                seeds[(seeds['set'] == s_) & (seeds['aoa'] == aoa)]['mae_m'].tolist()
            e.loc[(e['model'] == 'gru') & (e['h'] == 15), 'mae_m'] = np.mean(g15)
            sn = e[e['h'] == 0].sort_values('mae_m').iloc[0]
            hi = e[e['h'] > 0].sort_values('mae_m').iloc[0]
            rows.append(['25×25 regression', label, 'yes' if aoa else 'no', f"{fmt(sn['mae_m'], 1)} ({names[sn['model']]})",
                         f"{fmt(hi['mae_m'], 1)} ({names[hi['model']]}, h = {int(hi['h'])})", fmt(guess_r, 1),
                         f"{100 * (1 - hi['mae_m'] / sn['mae_m']):.0f} %"])
    md = json.loads((REC / 'error_audit' / 'macro_uniform_nlos' / 'error_distribution.json').read_text())
    for grp, label, aoa in (('multi', 'multi-antenna', 'yes'), ('single', 'single-antenna', 'no')):
        snap = min(((md[f'{m}/snap/{grp}']['mean_m'], m) for m in ('xgboost', 'random_forest')))
        full = min(((md[f'{m}/full/{grp}']['mean_m'], m) for m in ('xgboost', 'random_forest')))
        rows.append(['Macro cell, uniform NLOS', label, aoa, f'{fmt(snap[0], 1)} ({names[snap[1]]})',
                     f'{fmt(full[0], 1)} ({names[full[1]]}, h = 5)', fmt(md[f'xgboost/snap/{grp}']['constant_guess_mean_m'], 1),
                     f'{100 * (1 - full[0] / snap[0]):.0f} %'])
    write('T2_cross_study', ['Study', 'Setting', 'AoA', 'Best snapshot (m)', 'Best with history (m)', 'Constant guess (m)', 'Error reduction'],
          rows, 'Mean position error of the best model without history (h = 0) and with history (any depth tested), against always '
          'guessing the mean position. Grid: XGBoost, RF single run, CNN and GRU three seeds, h up to 15. 25×25: GRU at h = 15 '
          'three seeds, others single run. Macro: XGBoost and RF only (first seed of the error audit); the seven-family result '
          'is in Section 7.', 'lllllll')


# ── T3 25x25: best tree vs GRU ───────────────────────────────────────────────
def t3():
    a = pd.read_csv(REC / 'regression_25x25_2026_10' / 'sequence_vs_trees' / 'all_mae.csv')
    rows = []
    for s_, label in (('umilos', 'UMi LOS'), ('nlos', 'uniform NLOS'), ('mixed', 'mixed')):
        f = pd.read_csv(REC / 'regression_25x25_2026_10' / 'sequence_vs_trees' / f'{s_}_gru_h15_seeds12.csv')
        for aoa in (False, True):
            e = a[(a['set'] == s_) & (a['aoa'] == aoa)]
            trees = e[e['model'].isin(['xgboost', 'rf'])].sort_values('mae_m').iloc[0]
            g = e[(e['model'] == 'gru') & (e['h'] == 15)]['mae_m'].tolist() + \
                f[f['experiment'] == ('BASE_A' if aoa else 'BASE')]['mae_m'].tolist()
            cnn = e[(e['model'] == 'cnn') & (e['h'] == 15)]['mae_m'].iloc[0]
            rows.append([label, 'yes' if aoa else 'no',
                         f"{fmt(trees['mae_m'], 1)} ({'XGBoost' if trees['model'] == 'xgboost' else 'RF'}, h = {int(trees['h'])})",
                         f'{fmt(cnn, 1)}', f'{fmt(np.mean(g), 1)} ± {np.std(g):.1f}', f"{fmt(trees['mae_m'] - np.mean(g), 1)}"])
    write('T3_25x25_trees_vs_gru', ['Propagation', 'AoA', 'Best tree, any depth (m)', 'CNN h = 15 (m)', 'GRU h = 15 (m)', 'GRU gain over best tree (m)'],
          rows, '25×25 regression (five pooled device profiles, NE BS, fixed 4° AoA noise): mean 3D position error. Trees at h = 0, 3, '
          '7, 15 with parameters tuned at h = 3 (single runs); CNN single run; GRU mean ± standard deviation over three seeds. '
          'Constant guess 37.3 m.', 'llllll')


# ── T5 grid baselines under clean and imperfect history ──────────────────────
def t5():
    irr = REC / 'history_irregular'
    def irr_mean(folder, model, cond):
        d = pd.read_csv(irr / folder / 'history_irregular.csv')
        return d[(d['model'] == model) & (d['condition'] == cond)]['mae'].mean()
    tf = pd.read_csv(REC / 'tracking_filter' / 'ne_mixed_checks' / 'tracking_filter.csv')
    def filt(motion, cond, method='filter'):
        return tf[(tf['snapshot_model'] == 'rf') & (tf['motion'] == motion) & (tf['condition'] == cond) & (tf['method'] == method)]['mae'].iloc[0]
    conds = ('regular', 'mask30', 'gap2')
    rows = [['RF, current report only', 'no'] + [fmt(filt('learned', c, 'snapshot')) for c in conds],
            ['XGBoost, 10 older reports', 'learned (window)'] + [fmt(irr_mean('ne_mixed', 'xgboost', c)) for c in conds],
            ['1D-CNN, 10 older reports', 'learned (sequence)'] + [fmt(irr_mean('ne_mixed_cnn', 'cnn', c)) for c in conds],
            ['GRU, 10 older reports', 'learned (sequence)'] + [fmt(irr_mean('ne_mixed', 'gru', c)) for c in conds],
            ['RF + HMM filter, generic motion (2 m)', 'motion model'] + [fmt(filt('generic2', c)) for c in conds],
            ['RF + HMM filter, learned motion', 'motion model'] + [fmt(filt('learned', c)) for c in conds]]
    write('T5_grid_baselines', ['Model', 'Use of history', 'Regular (m)', '30 % missing (m)', 'Uneven gaps, mean 2 (m)'],
          rows, '15×15 grid, mixed propagation, BS beyond the corner, RSS and SINR only: mean position error with clean history '
          'and with imperfect history (each older report missing with probability 0.3; reports at random gaps with mean 2 steps). '
          'Learned models are trained with the same imperfection; CNN three seeds, GRU two, others single run. The HMM filter '
          'is causal (past reports only). On this grid every step moves to a neighbouring cell, which suits a motion model.',
          'llrrr')


if __name__ == '__main__':
    t2()
    t3()
    t5()
